"""Writes problems.h (the 300 problems as C arrays) from problems.json. No answers go in it."""
import json, sys, os
P = json.load(open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "problems", "problems.json")))
o = ["/* the 300 problems, generated by gen_problems.py from problems.json (no answers) */", "#include <stdint.h>",
     "typedef struct { char id[5]; uint8_t seq, n, nq; int32_t x[12], y[12], q[2]; } bt_problem;",
     f"#define BT_NPROBLEMS {len(P)}", "static const bt_problem BT_PROBLEMS[] = {"]
for p in P:
    if p["type"] == "sequence":
        t = p["terms"]; o.append('  {"%s",1,%d,0,{%s},{0},{0}},' % (p["id"], len(t), ",".join(map(str, t))))
    else:
        e = p["examples"]
        o.append('  {"%s",0,%d,%d,{%s},{%s},{%s}},' % (p["id"], len(e), len(p["questions"]), ",".join(str(a) for a, _ in e),
                 ",".join(str(b) for _, b in e), ",".join(map(str, p["questions"]))))
o.append("};")
open(sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "problems.h"), "w").write("\n".join(o) + "\n")
